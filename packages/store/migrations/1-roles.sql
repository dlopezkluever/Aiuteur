-- One-time cluster bootstrap: only this migration needs the installation's
-- bootstrap superuser. All application DDL runs as owner; no runtime uses it.
DO $$
BEGIN
  IF NOT EXISTS (SELECT FROM pg_roles WHERE rolname = 'owner') THEN
    CREATE ROLE owner NOLOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOINHERIT NOBYPASSRLS;
    CREATE ROLE app LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOINHERIT NOBYPASSRLS;
    CREATE ROLE scheduler LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOINHERIT NOBYPASSRLS;
    CREATE ROLE identity LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOINHERIT NOBYPASSRLS;
    CREATE ROLE operator_read LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOINHERIT NOBYPASSRLS;
    CREATE ROLE backup LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOINHERIT BYPASSRLS;
  END IF;
END $$;
DO $$ BEGIN EXECUTE format('GRANT CREATE ON DATABASE %I TO owner', current_database()); END $$;
REVOKE CREATE ON SCHEMA public FROM PUBLIC;
ALTER TABLE public.migrations OWNER TO owner;
GRANT SELECT ON public.migrations TO backup;
