import { existsSync, readFileSync, writeFileSync } from "node:fs";
import {
  ACTOR_KINDS, ATTEMPT_ORIGINS, AUDIT_ACTIONS, BILLED, CALL_ROLES, DECISION_TYPES, EVENT_TYPES, FAILURE_CLASSES, GENERATION_OUTCOMES,
  IDEMPOTENT_OPERATIONS, JOB_CLASSES, MEDIA_ORIGINS, REFERENCE_IMAGE_TYPES, JOB_STATES, OPERATION_CLASSES, REVISION_CAUSES, WORKFLOW_OPERATIONS,
} from "@aiuteur/contract";

const list = (values: readonly string[]) => values.map((value) => `'${value.replaceAll("'", "''")}'`).join(", ");
const check = process.argv.includes("--check");
const dir = process.env["MIGRATIONS_DIR"];
const migration = (name: string) => dir ? new URL(`file://${dir}/${name}`) : new URL(`../migrations/${name}`, import.meta.url);

// Migration 3 is merged and immutable: it is wholly generated.
const audit = migration("3-audit-vocabulary.sql");
const auditSql = `-- Generated by scripts/vocabulary.ts from contract.AUDIT_ACTIONS.\nSET LOCAL ROLE owner;\nALTER TABLE auth.audit_event ADD CONSTRAINT audit_action CHECK (action IN (${list(AUDIT_ACTIONS)}));\n`;
if (dir) { /* test override carries only the history migrations */ } else if (check) {
  if (readFileSync(audit, "utf8") !== auditSql) throw new Error("D3: generated vocabulary migration differs");
} else writeFileSync(audit, auditSql);

interface Vocabulary { readonly table: string; readonly constraint: string; readonly column: string; readonly values: readonly string[]; readonly replace?: true }
// Each migration carries its CHECKs in one generated block between markers. Vocabularies only grow (D3: an
// expand migration), so a merged migration's block is generated from the prefix of the set it was written with;
// a later migration that adds values drops and re-adds the constraint with the whole set (`replace`).
export const VOCABULARY_BLOCKS: Readonly<Record<string, readonly Vocabulary[]>> = {
  "5-history.sql": [
    { table: "revision", constraint: "revision_cause", column: "cause", values: REVISION_CAUSES },
    { table: "revision", constraint: "revision_actor_kind", column: "actor_kind", values: ACTOR_KINDS },
    { table: "attempt", constraint: "attempt_origin", column: "origin", values: ATTEMPT_ORIGINS.slice(0, 2) },
    { table: "idempotency", constraint: "idempotency_operation", column: "operation", values: IDEMPOTENT_OPERATIONS.slice(0, 2) },
  ],
  "6-generation-and-jobs.sql": [
    { table: "idempotency", constraint: "idempotency_operation", column: "operation", values: IDEMPOTENT_OPERATIONS.slice(0, 4), replace: true },
    { table: "generation", constraint: "generation_operation", column: "operation", values: WORKFLOW_OPERATIONS },
    { table: "generation", constraint: "generation_operation_class", column: "operation_class", values: OPERATION_CLASSES },
    { table: "job", constraint: "job_class", column: "class", values: JOB_CLASSES },
    { table: "job", constraint: "job_state", column: "state", values: JOB_STATES },
    { table: "job", constraint: "job_failure_class", column: "failure_class", values: FAILURE_CLASSES },
    { table: "job", constraint: "job_billed", column: "billed", values: BILLED },
    { table: "generation_run", constraint: "generation_run_state", column: "state", values: JOB_STATES },
    { table: "generation_run", constraint: "generation_run_failure_class", column: "failure_class", values: FAILURE_CLASSES },
    { table: "generation_run", constraint: "generation_run_billed", column: "billed", values: BILLED },
    { table: "generation_call", constraint: "generation_call_role", column: "role", values: CALL_ROLES },
    { table: "generation_settlement", constraint: "generation_settlement_outcome", column: "outcome", values: GENERATION_OUTCOMES },
    { table: "decision", constraint: "decision_type", column: "type", values: DECISION_TYPES },
    { table: "event", constraint: "event_type", column: "type", values: EVENT_TYPES },
  ],
  "7-media.sql": [
    { table: "attempt", constraint: "attempt_origin", column: "origin", values: ATTEMPT_ORIGINS, replace: true },
    { table: "idempotency", constraint: "idempotency_operation", column: "operation", values: IDEMPOTENT_OPERATIONS, replace: true },
    { table: "media", constraint: "media_origin", column: "origin", values: MEDIA_ORIGINS },
    { table: "media", constraint: "media_content_type", column: "content_type", values: REFERENCE_IMAGE_TYPES },
  ],
};
/** The constraints whose live CHECK must equal a contract set, with that set (the latest definition wins). */
export const LIVE_VOCABULARY: ReadonlyMap<string, readonly string[]> = new Map(Object.values(VOCABULARY_BLOCKS).flat().map((v) => [v.constraint, v.values]));

const begin = "-- BEGIN GENERATED VOCABULARY\n";
const end = "-- END GENERATED VOCABULARY\n";
for (const [name, vocabularies] of Object.entries(VOCABULARY_BLOCKS)) {
  const file = migration(name);
  if (dir && !existsSync(file)) continue;
  const source = readFileSync(file, "utf8");
  const block = vocabularies.map((v) => (v.replace ? `ALTER TABLE accounts.${v.table} DROP CONSTRAINT ${v.constraint};\n` : "") +
    `ALTER TABLE accounts.${v.table} ADD CONSTRAINT ${v.constraint} CHECK (${v.column} IN (${list(v.values)}));\n`).join("");
  const generated = source.slice(0, source.indexOf(begin) + begin.length) + block + source.slice(source.indexOf(end));
  if (check) {
    if (source !== generated) throw new Error(`D3: generated vocabulary block of ${name} differs`);
  } else writeFileSync(file, generated);
}
