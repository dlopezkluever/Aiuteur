import { readFileSync, writeFileSync } from "node:fs";
import { AUDIT_ACTIONS } from "@aiuteur/contract";

const file = new URL("../migrations/3-audit-vocabulary.sql", import.meta.url);
const values = AUDIT_ACTIONS.map((value) => `'${value.replaceAll("'", "''")}'`).join(", ");
const sql = `-- Generated by scripts/vocabulary.ts from contract.AUDIT_ACTIONS.\nSET LOCAL ROLE owner;\nALTER TABLE auth.audit_event ADD CONSTRAINT audit_action CHECK (action IN (${values}));\n`;
if (process.argv.includes("--check")) {
  if (readFileSync(file, "utf8") !== sql) throw new Error("D3: generated vocabulary migration differs");
} else writeFileSync(file, sql);
